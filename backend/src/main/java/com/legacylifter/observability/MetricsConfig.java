package com.legacylifter.observability;

import io.micrometer.core.instrument.Counter;
import io.micrometer.core.instrument.MeterRegistry;
import io.micrometer.core.instrument.Timer;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

/**
 * Registers all custom LegacyLifter metrics with Micrometer.
 *
 * <p>These metrics are automatically scraped by Prometheus via the
 * {@code /actuator/prometheus} endpoint and visualised in Grafana.</p>
 */
@Configuration
public class MetricsConfig {

    /** Counter: total Java files analyzed across all projects. */
    @Bean
    public Counter filesProcessedCounter(MeterRegistry registry) {
        return Counter.builder("ll.analysis.files.processed")
                .description("Total Java files analyzed")
                .register(registry);
    }

    /** Counter: total code issues detected (tagged by category). */
    @Bean
    public Counter issuesDetectedCounter(MeterRegistry registry) {
        return Counter.builder("ll.issues.detected")
                .description("Total code issues detected")
                .tag("category", "all")
                .register(registry);
    }

    /** Counter: total modernization suggestions generated by the AI engine. */
    @Bean
    public Counter suggestionsGeneratedCounter(MeterRegistry registry) {
        return Counter.builder("ll.modernization.suggestions")
                .description("Modernization suggestions generated")
                .register(registry);
    }

    /** Counter: total modernization suggestions applied by users. */
    @Bean
    public Counter suggestionsAppliedCounter(MeterRegistry registry) {
        return Counter.builder("ll.modernization.applied")
                .description("Modernization suggestions applied")
                .register(registry);
    }

    /** Counter: total GitHub Pull Requests created. */
    @Bean
    public Counter githubPrsCreatedCounter(MeterRegistry registry) {
        return Counter.builder("ll.github.pr.created")
                .description("GitHub pull requests created by LegacyLifter")
                .register(registry);
    }

    /** Counter: total JUnit test classes generated. */
    @Bean
    public Counter testsGeneratedCounter(MeterRegistry registry) {
        return Counter.builder("ll.tests.generated")
                .description("Test classes generated by the AI test generator")
                .register(registry);
    }

    /** Timer: end-to-end duration of a full analysis run. */
    @Bean
    public Timer analysisTimer(MeterRegistry registry) {
        return Timer.builder("ll.analysis.duration")
                .description("End-to-end duration of a static analysis run")
                .publishPercentiles(0.50, 0.95, 0.99)
                .register(registry);
    }

    /** Timer: LLM call latency (Ollama or OpenAI). */
    @Bean
    public Timer llmRequestTimer(MeterRegistry registry) {
        return Timer.builder("ll.llm.request.duration")
                .description("Latency of LLM API calls (modernization + test generation)")
                .publishPercentiles(0.50, 0.95, 0.99)
                .register(registry);
    }

    /** Counter: LLM token consumption (approximate). */
    @Bean
    public Counter llmTokensUsedCounter(MeterRegistry registry) {
        return Counter.builder("ll.llm.tokens.used")
                .description("Approximate LLM tokens consumed")
                .register(registry);
    }
}
